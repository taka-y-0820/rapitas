/**
 * ClaudeCodeAgent Prompt Builder
 *
 * Constructs structured prompts from task analysis data for consumption by the Claude Code CLI.
 * Not responsible for spawning processes or parsing output.
 */

import { randomUUID } from 'node:crypto';
import type { AgentTask } from '../base-agent';
import { createLogger } from '../../../config/logger';

const logger = createLogger('claude-code-agent');

/**
 * Builds a structured prompt from AI task analysis results.
 * Falls back to a simple prompt with workflow instructions when no analysis is available.
 *
 * @param task - Task definition including optional AI analysis / AIタスク定義
 * @param workDir - Resolved working directory for the task / タスクの作業ディレクトリ
 * @param logPrefix - Logger prefix for this agent instance / ロガーのプレフィックス
 * @returns Full prompt string ready to pipe to Claude Code CLI / Claude Code CLIに渡すプロンプト文字列
 */
export function buildStructuredPrompt(task: AgentTask, workDir: string, logPrefix: string): string {
  // Use optimized prompt if available (generated by PromptOptimizationPanel)
  if (task.optimizedPrompt) {
    logger.info(`${logPrefix} Using optimized prompt (${task.optimizedPrompt.length} chars)`);
    // Prepend working directory instruction to optimized prompt
    return `**CRITICAL: You MUST work in this directory ONLY: ${workDir}**\n**DO NOT modify files outside this directory.**\n\n${task.optimizedPrompt}`;
  }

  const analysis = task.analysisInfo;

  if (!analysis) {
    return buildSimplePrompt(task, workDir);
  }

  return buildAnalysisPrompt(task, workDir);
}

/**
 * Builds a minimal prompt appending workflow instructions when no AI analysis is available.
 *
 * @param task - Task to build prompt for / プロンプトを構築するタスク
 * @param workDir - Working directory for the task / タスクの作業ディレクトリ
 * @returns Simple prompt string / シンプルなプロンプト文字列
 */
function buildSimplePrompt(task: AgentTask, workDir: string): string {
  const transportPath = `${workDir}/.wf-${randomUUID()}.md`;
  const basePrompt = task.description || task.title;
  const freshnessRule =
    'Create a new report from the current code and current task requirements in this run before uploading. Never upload an existing transport file or copy a previous report unchanged; interrupted or rejected reports are stale evidence. The transport path below is unique to this invocation.';
  const port = process.env.PORT || '3001';
  const workflowInstructions = [
    `\n\n## Working Directory`,
    `**CRITICAL: You MUST work in this directory ONLY: ${workDir}**`,
    `**DO NOT modify files outside this directory.**`,
    ``,
    `## Workflow Steps`,
    `Please execute the task in the following order. **research/question/plan/verify are NOT files — each is a DB row (WorkflowFile.content), saved exclusively via the API below. There is no research.md/plan.md/verify.md on disk; do not refer to them as files when narrating progress ("DBに保存しました", not "research.mdを保存しました").**`,
    freshnessRule,
    `1. Research → record findings to the DB (fileType=research)`,
    `   - **調査は時間を区切る**: 問題を理解できる程度に調べたら、すぐ調査結果をDBに保存して次へ進む。完全に原因特定できなくても、現時点の所見・仮説・未解明点を保存すること（延々と grep/read を繰り返さない）。`,
    `   - **調査で Task/Agent（サブエージェント）を起動しない**: 自分で直接調べる。サブエージェントは時間とトークンを浪費する。`,
    `2. If unclear points exist, save a question to the DB (fileType=question) + AskUserQuestion (MUST use multiple-choice options — see Question Format below)`,
    task.autoApprovePlan
      ? `3. Record a plan to the DB (fileType=plan) → **Plan will be auto-approved. Proceed to implementation immediately after saving.**`
      : `3. Record a plan to the DB (fileType=plan) → **Stop implementation and wait for approval**`,
    task.autoApprovePlan
      ? `4. Implement immediately (auto-approved)`
      : `4. Implement after approval`,
    `5. Record verification results to the DB (fileType=verify)`,
    ``,
    `**保存API（UTF-8厳守）— 実体はDB行、一時ファイルは送信用の使い捨て器にすぎない**:`,
    freshnessRule,
    `1. 保存内容を Write ツールで UTF-8 の一時ファイルに書き出す（例: \`${transportPath}\`。プロジェクトルートには作らない。このファイルはHTTPリクエストボディを渡すためだけの使い捨てで、保存の実体ではない）`,
    `2. 生ファイルを送信: \`curl.exe -X PUT http://127.0.0.1:${port}/workflow/tasks/${task.id}/files/<research|question|plan|verify> -H "Content-Type: text/markdown; charset=utf-8" --data-binary @${transportPath}\` — この呼び出しでDBの WorkflowFile 行に保存される（これが唯一の永続化先）`,
    `3. 2xx 応答を確認できたらDB保存は完了。一時ファイルは役目を終えたので削除する（削除してもDBの内容には一切影響しない）`,
    `- **重要**: Windows では PowerShell のパイプや \`-d\` のインライン文字列で curl に渡さない（既定の US-ASCII で日本語が "?" に化ける）。必ず上記の一時ファイル+\`--data-binary\` 方式・\`curl.exe\` を使う。`,
    `- 文字化け("?"置換)を検出すると保存APIは HTTP 422 で拒否する。その場合は UTF-8 で再送信する。`,
    `- **2xx を確認したら、同じ fileType を再送信しない。** パス区切り文字（\`C:\\\\...\` と \`/c/...\`）を変えて2回叩くようなリトライは不要かつ有害 — 2回目は状態遷移済みのため 400 で拒否されるか、無駄な二重リクエストになるだけ。1回目の \`--data-binary @${transportPath}\`（バックスラッシュ区切りのままでよい）で 2xx が返れば、それ以上の確認や再送信は不要。`,
    ``,
    `## Question Format (MANDATORY)`,
    `When asking questions via AskUserQuestion, you MUST provide multiple-choice options.`,
    `- Always include 2-4 selectable options`,
    `- Use this format: provide options array in the AskUserQuestion tool input`,
    `- Free-text questions are only allowed for truly open-ended inputs (e.g., API keys, custom paths)`,
    `- For yes/no questions, provide "はい" and "いいえ" as options`,
    `- For scope/approach questions, provide concrete choices (e.g., "A: minimal change", "B: full refactor")`,
    ``,
    `**Important Notes**:`,
    `- Do not use plan mode (EnterPlanMode), implement code directly. Do not stop at planning, make sure to complete file creation and editing.`,
    `- **Never create files in the project root. Temporary files are no exception.**`,
    `- research/question/plan/verify are DB records, not files — save all of them exclusively via the above API.`,
    `- File creation in project root using Write tool or Bash tool (mkdir/echo) is prohibited.`,
    `- **Do not create temporary files like implementation_*.md, temp_*.md, *_content.json, etc.**`,
  ].join('\n');
  return basePrompt + workflowInstructions;
}

/**
 * Builds a detailed prompt from AI task analysis data including subtasks and workflow steps.
 *
 * @param task - Task with analysis info populated / analysisInfoが設定されたタスク
 * @param workDir - Working directory for the task / タスクの作業ディレクトリ
 * @returns Detailed structured prompt string / 詳細な構造化プロンプト文字列
 */
function buildAnalysisPrompt(task: AgentTask, workDir: string): string {
  const transportPath = `${workDir}/.wf-${randomUUID()}.md`;
  const analysis = task.analysisInfo!;
  const freshnessRule =
    'Create a new report from the current code and current task requirements in this run before uploading. Never upload an existing transport file or copy a previous report unchanged; interrupted or rejected reports are stale evidence. The transport path below is unique to this invocation.';
  const port = process.env.PORT || '3001';

  // Priority label mapping
  const priorityLabels: Record<string, string> = {
    low: 'Low',
    medium: 'Medium',
    high: 'High',
    urgent: 'Urgent',
  };

  // Complexity label mapping
  const complexityLabels: Record<string, string> = {
    simple: 'Simple',
    medium: 'Medium',
    complex: 'Complex',
  };

  const sections: string[] = [];
  sections.push('# Task Implementation Instructions');
  sections.push('');

  sections.push('## Working Directory');
  sections.push(`**CRITICAL: You MUST work in this directory ONLY: ${workDir}**`);
  sections.push(`**DO NOT modify files outside this directory.**`);
  sections.push(
    `**All file operations (Read, Write, Bash commands) must target files within: ${workDir}**`,
  );
  sections.push('');

  sections.push('## Overview');
  sections.push(`**Task Name:** ${task.title}`);
  sections.push(`**Analysis Summary:** ${analysis.summary}`);
  sections.push(`**Complexity:** ${complexityLabels[analysis.complexity] || analysis.complexity}`);
  sections.push(`**Estimated Total Hours:** ${analysis.estimatedTotalHours} hours`);
  sections.push('');

  if (task.description) {
    sections.push('## Task Details');
    sections.push(task.description);
    sections.push('');
  }

  if (analysis.subtasks && analysis.subtasks.length > 0) {
    sections.push('## Implementation Steps');
    sections.push('Please implement the task in the following order:');
    sections.push('');

    // `order` is a unique explicit sequence key (used as the dependency
    // identifier via `subtasks.find(s => s.order === depOrder)`), so there are
    // no ties to resolve — the sort is already deterministic.
    // determinism-ok: unique sequence key, no ties.
    const sortedSubtasks = [...analysis.subtasks].sort((a, b) => a.order - b.order);

    for (const subtask of sortedSubtasks) {
      const priorityLabel = priorityLabels[subtask.priority] || subtask.priority;
      sections.push(`### ${subtask.order}. ${subtask.title}`);
      sections.push(`- **Description:** ${subtask.description}`);
      sections.push(`- **Estimated Hours:** ${subtask.estimatedHours} hours`);
      sections.push(`- **Priority:** ${priorityLabel}`);

      if (subtask.dependencies && subtask.dependencies.length > 0) {
        const depTitles = subtask.dependencies
          .map((depOrder) => {
            const dep = analysis.subtasks.find((s) => s.order === depOrder);
            return dep ? `${depOrder}. ${dep.title}` : `Step ${depOrder}`;
          })
          .join(', ');
        sections.push(`- **Dependencies:** Execute after completion of ${depTitles}`);
      }
      sections.push('');
    }
  }

  if (analysis.reasoning) {
    sections.push('## Implementation Approach Rationale');
    sections.push(analysis.reasoning);
    sections.push('');
  }

  if (analysis.tips && analysis.tips.length > 0) {
    sections.push('## Implementation Hints');
    for (const tip of analysis.tips) {
      sections.push(`- ${tip}`);
    }
    sections.push('');
  }

  sections.push('## Workflow Steps');
  sections.push(
    'Please execute the task in the following steps. **research/question/plan/verify are NOT files — each is a DB row (WorkflowFile.content), saved exclusively via the API below. There is no research.md/plan.md/verify.md on disk; when narrating progress, say "saved to the DB", not "saved research.md".**',
  );
  sections.push('');
  sections.push(
    '1. **Research**: Investigate the codebase and record findings to the DB (fileType=research)',
  );
  sections.push(
    '   - **Time-box the investigation**: once you understand the problem well enough, record your findings to the DB and move on. If you cannot fully pin the root cause, record your findings, hypotheses, and open questions instead of grepping/reading indefinitely.',
  );
  sections.push(
    '   - **Do NOT spawn sub-agents (Task/Agent tool) to investigate** — investigate directly; sub-agents waste time and tokens.',
  );
  sections.push(
    '2. **Questions**: If there are unclear points, record a question to the DB (fileType=question) and ask with AskUserQuestion.',
  );
  sections.push(
    '   - **MANDATORY**: Always provide multiple-choice options (2-4 choices) in AskUserQuestion',
  );
  sections.push('   - Provide options array in the tool input, NOT as plain text');
  sections.push('   - For yes/no questions: options = ["はい", "いいえ"]');
  sections.push(
    '   - For scope questions: options = ["A: minimal", "B: standard", "C: comprehensive"]',
  );
  sections.push(
    '   - Free-text input is ONLY for open-ended inputs (API keys, custom paths, etc.)',
  );
  sections.push('   - Skip questions only if requirements are completely clear');
  sections.push(
    task.autoApprovePlan
      ? '3. **Planning**: Record a plan to the DB (fileType=plan) reflecting research results and answers. **Plan will be auto-approved. Proceed to implementation immediately after saving.**'
      : '3. **Planning**: Record a plan to the DB (fileType=plan) reflecting research results and answers. **After saving, stop implementation here and wait for approval**',
  );
  sections.push(
    task.autoApprovePlan
      ? '4. **Implementation**: Implement immediately (auto-approved — do not wait for user approval)'
      : '4. **Implementation**: Implement after user approves the plan (do not ask questions at this stage)',
  );
  sections.push(
    '5. **Verification**: Record implementation results to the DB (fileType=verify). If you made NO code changes because none were actually needed, you MUST state that reason explicitly (e.g. "変更不要: 既に正しく実装されている") — a passing verify with an empty diff and no such justification is rejected as an incomplete (silently-skipped) implementation.',
  );
  sections.push('');
  sections.push('### How to Save Workflow Records (UTF-8 — IMPORTANT)');
  sections.push(
    'Each record is persisted as a DB row (WorkflowFile.content) via the API below — this is the ONLY persistence; there is no research.md/plan.md/verify.md file on disk. To avoid character corruption (Japanese turning into "?"), DO NOT inline the content into the shell command.',
  );
  sections.push('');
  sections.push('**Procedure (per record):**');
  sections.push(
    freshnessRule,
    `1. Write the markdown to a UTF-8 temp file with your Write tool inside the working directory (e.g. \`${transportPath}\`) — NOT in the project root. This file is a disposable transport container for the HTTP request body, not the persisted artifact.`,
  );
  sections.push(
    `2. Send the raw file as the body: \`curl.exe -X PUT http://127.0.0.1:${port}/workflow/tasks/${task.id}/files/<research|question|plan|verify> -H "Content-Type: text/markdown; charset=utf-8" --data-binary @${transportPath}\` — this call is what actually persists the content, to the WorkflowFile DB row.`,
  );
  sections.push(
    '3. Once you see a 2xx response, the DB save is complete. Delete the temp file — it has served its purpose and its deletion has no effect on the saved DB content.',
  );
  sections.push('');
  sections.push('**Rules:**');
  sections.push(
    '- On Windows, NEVER pipe content to curl in PowerShell and NEVER use `-d` with inline Japanese — PowerShell\'s default US-ASCII OutputEncoding corrupts it to "?". Always use the temp-file + `--data-binary` method above, with `curl.exe` (not the PowerShell `curl` alias).',
  );
  sections.push(
    '- If the content is corrupted ("?" replacement), the API rejects the save with HTTP 422 — re-send as UTF-8 using the method above.',
  );
  sections.push(
    '- **Once you see a 2xx, do NOT re-send the same fileType.** Retrying with a different path style (e.g. `C:\\\\...` vs `/c/...`) is unnecessary and harmful — the second call either gets rejected (the status already moved on) or is just a wasted duplicate request. A 2xx on the first `--data-binary @<path>` call (backslash path is fine) means the save is done; no further confirmation or re-send is needed.',
  );
  sections.push(
    '- The ONLY file you may create outside the proper output is the single transmission temp file above (inside the working directory). Never create files in the project root.',
  );
  sections.push('');

  sections.push('## Execution Instructions');
  sections.push('Please implement the task from start to finish following the above steps.');
  sections.push('After completing each step, proceed to the next step.');
  sections.push('If you have unclear points, please ask questions.');
  sections.push('');
  sections.push('## Important Notes');
  sections.push(
    `- **CRITICAL: You MUST work ONLY in ${workDir}. DO NOT modify files outside this directory.**`,
  );
  sections.push(
    `- **Verify file paths before any operation. All paths must be within ${workDir}.**`,
  );
  sections.push('- **Do not use plan mode (EnterPlanMode).** Implement code directly.');
  sections.push('- Do not stop at planning, make sure to complete file creation and editing.');
  sections.push('- **Never create files in the project root.**');
  sections.push(
    '- research/question/plan/verify are DB records, not files — save all of them exclusively via the above API.',
  );
  sections.push('- File creation using Write tool or Bash tool (mkdir/echo) is prohibited.');
  sections.push('- Use Write, Edit, and other tools to actually change the code.');

  return sections.join('\n');
}
